def tool_short(tool_name: str) -> str:
    """mcp__claude_ai_Slack__slack_send_message → slack_send_message"""
    return tool_name.rsplit("__", 1)[-1]


def is_slack_tool(tool_name: str) -> bool:
    return tool_name.startswith("mcp__") and "slack" in tool_name.lower()


def clean(text) -> str:
    """흔적 검사용: 전각·호환 문자를 펴고 폭 0 문자를 지운다."""
    text = unicodedata.normalize("NFKC", str(text or ""))
    return re.sub(r"[​-‏‪-‮⁠-⁤﻿­]", "", text)


def same_text(text) -> str:
    """카드에 보인 글과 보낼 글 대조용: 바깥 코드 블록·<pre>/<div> 하나를 벗기고 공백만 맞춘다."""
    text = html.unescape(str(text or "")).replace("\r\n", "\n").strip()
    for pattern in (r"```[^\n]*\n(.*?)\n?```", r"<(pre|div|p)\b[^>]*>(.*)</\1>"):
        m = re.fullmatch(pattern, text, re.DOTALL | re.IGNORECASE)
        if m:
            text = m.group(m.lastindex).strip()
    return re.sub(r"\s+", " ", text).strip()


def canonical(tool_input: dict) -> dict:
    out = {}
    for key, value in sorted(tool_input.items()):
        if value is None or value == "" or value is False:
            continue  # 빈 값·False 는 안 준 것과 같게 본다
        if key == "message" and isinstance(value, str):
            value = value.replace("\r\n", "\n").replace("\r", "\n")
        out[key] = value
    return out


def approval_code(tool: str, tool_input: dict) -> str:
    blob = json.dumps({"tool": tool, "input": canonical(tool_input)}, ensure_ascii=False, sort_keys=True)
    return hashlib.sha256(blob.encode("utf-8", "surrogatepass")).hexdigest()[:6]


def strings(value):
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for v in value.values():
            yield from strings(v)
    elif isinstance(value, list):
        for v in value:
            yield from strings(v)


def find_traces(tool_input: dict):
    found = []
    for text in strings(tool_input):
        text = clean(text)
        last = next((line for line in reversed(text.splitlines()) if line.strip()), "")
        for pattern, name in TRACES:
            # 줄 끝 서명은 마지막 줄에서만 본다(목록의 '- Claude' 같은 줄은 막지 않는다)
            target = last if name in {"— Claude 서명", "Claude 작성 서명", "🤖 서명"} else text
            if re.search(pattern, target, FLAGS) and name not in found:
                found.append(name)
    return found


def parse_time(value):
    try:
        t = dt.datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    except ValueError:
        return None
    return t if t.tzinfo else None  # 시간대 없는 시각은 믿지 않는다


def label_ok(label, want: str) -> bool:
    return isinstance(label, str) and bool(re.fullmatch(re.escape(want) + r"(\s*\((추천|Recommended)\))?", label.strip()))


def destination_problems(tool: str, tool_input: dict, question: str):
    """카드 질문에 보낼 곳이 사람이 읽게 적혀 있는지."""
    problems = []
    channel = str(tool_input.get("channel_id") or "").strip()
    if channel and channel not in question:
        problems.append(f"카드 질문에 보낼 곳의 채널 ID({channel})가 없다")
    if tool in MESSAGE_TOOLS:
        if tool_input.get("thread_ts"):
            if "스레드 답글" not in question:
                problems.append("스레드 답글인데 카드 질문에 '스레드 답글'이 없다")
        else:
            want = "DM" if channel[:1] in {"U", "W", "D"} else "새 글"
            if want not in question or "스레드 답글" in question:
                problems.append(f"카드 질문에 '{want}'가 없거나 '스레드 답글'로 잘못 적었다")
        if tool_input.get("reply_broadcast") and "채널에도" not in question:
            problems.append("채널에도 올리는데(reply_broadcast) 카드 질문에 '채널에도'가 없다")
    if tool_input.get("post_at"):
        try:
            when = dt.datetime.fromtimestamp(int(tool_input["post_at"]), KST).strftime("%m/%d %H:%M")
        except (TypeError, ValueError, OverflowError, OSError):
            when = None
        if not when or when not in question:
            problems.append(f"예약 시각({when or tool_input.get('post_at')}, 한국 시간 MM/DD HH:MM)이 카드 질문에 없다")
    return problems


def approvals(transcript_path: str, code: str):
    """대화 기록에서 '승인 <code>' 카드 결과를 찾는다. AskUserQuestion 을 실제로 부른 결과만 센다."""
    asked_ids = set()
    found = []
    with open(transcript_path, encoding="utf-8", errors="ignore") as f:
        for line in f:
            if '"AskUserQuestion"' not in line and '"answers"' not in line:
                continue
            try:
                d = json.loads(line)
            except ValueError:
                continue
            if not isinstance(d, dict):
                continue
            message = d.get("message") if isinstance(d.get("message"), dict) else {}
            content = message.get("content") if isinstance(message.get("content"), list) else []
            if d.get("type") == "assistant":
                for block in content:
                    if isinstance(block, dict) and block.get("type") == "tool_use" and block.get("name") == "AskUserQuestion":
                        asked_ids.add(block.get("id"))
                continue
            result = d.get("toolUseResult")
            if d.get("type") != "user" or not isinstance(result, dict) or not isinstance(result.get("questions"), list):
                continue
            tool_use_id = next((b.get("tool_use_id") for b in content if isinstance(b, dict) and b.get("type") == "tool_result"), None)
            answers = result.get("answers") if isinstance(result.get("answers"), dict) else {}
            annotations = result.get("annotations") if isinstance(result.get("annotations"), dict) else {}
            for q in result["questions"]:
                if not isinstance(q, dict):
                    continue
                text = f"{q.get('header', '')}\n{q.get('question', '')}"
                if not re.search(r"승인\s*" + re.escape(code) + r"(?![0-9a-f])", text):
                    continue
                note = annotations.get(q.get("question", ""))
                found.append({
                    "id": f"{tool_use_id}:{code}",
                    "genuine": tool_use_id is not None and tool_use_id in asked_ids,
                    "time": parse_time(d.get("timestamp")),
                    "question": q,
                    "answer": answers.get(q.get("question", "")),
                    "note": (note.get("notes") if isinstance(note, dict) else note) or "",
                    "auto": bool(result.get("afkTimeoutMs") or result.get("followUp") or str(result.get("response") or "").strip()),
                })
    return found


def load_used():
    if not os.path.exists(STATE):
        return {}
    with open(STATE, encoding="utf-8") as f:
        data = json.load(f)  # 깨졌으면 예외 → 막는다(초기화로 승인을 되살리지 못하게)
    used = data.get("used")
    if not isinstance(used, dict):
        raise ValueError("used 가 dict 가 아니다")
    return used


def mark_used(approval_id: str, code: str, tool_name: str) -> bool:
    os.makedirs(os.path.dirname(STATE), exist_ok=True)
    with open(STATE + ".lock", "w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        used = load_used()
        if approval_id in used:
            return False
        used[approval_id] = {"code": code, "tool": tool_name, "at": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")}
        fd, tmp = tempfile.mkstemp(dir=os.path.dirname(STATE))
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            json.dump({"used": used}, f, ensure_ascii=False, indent=1)
        os.replace(tmp, STATE)
        return True


def deny(reason: str):
    print(json.dumps({"hookSpecificOutput": {
        "hookEventName": "PreToolUse",
        "permissionDecision": "deny",
        "permissionDecisionReason": f"{PREFIX} {reason}",
    }}, ensure_ascii=False))
    sys.exit(0)


def how_to_ask(tool: str, code: str, tool_input: dict) -> str:
    label = APPROVE_LABEL.get(tool, OTHER_LABEL)
    channel = tool_input.get("channel_id")
    if tool in MESSAGE_TOOLS:
        kind = "스레드 답글" if tool_input.get("thread_ts") else ("DM" if str(channel or "")[:1] in {"U", "W", "D"} else "새 글")
        extra = " 채널에도 같이 올려요." if tool_input.get("reply_broadcast") else ""
        if tool_input.get("post_at"):
            try:
                extra += " " + dt.datetime.fromtimestamp(int(tool_input["post_at"]), KST).strftime("%m/%d %H:%M") + " 예약."
            except (TypeError, ValueError, OverflowError, OSError):
                pass
        question = f"'<채널 이름>({channel})에 {kind}로 보낼까요?{extra}'"
        option = f"'{label}'(description 에 보낼 글 전체 그대로, preview 에도 같은 글)"
    else:
        question = f"'<무엇을 어디에 하는지>{f' ({channel})' if channel else ''} 진행할까요?'"
        option = f"'{label}'(description 에 할 일)"
    return (
        f"승인 코드는 {code}. AskUserQuestion 으로 header '승인 {code}', 질문 {question}, 선택지 {option}·'고치기'·'보내지 않기' 를 보여 준다."
        f" 사용자가 '{label}'를 고르면 이 입력 그대로 다시 부른다. 입력을 하나라도 바꾸면 코드가 바뀐다."
    )


def check_slack(payload: dict, tool_name: str):
    tool = tool_short(tool_name)
    if READ_ONLY.fullmatch(tool):
        return
    tool_input = payload.get("tool_input")
    if not isinstance(tool_input, dict):
        deny("도구 입력 형식을 읽지 못해 막았다.")

    traces = find_traces(tool_input)
    if traces:
        deny(f"글에 Claude 가 썼다는 흔적이 있다({', '.join(traces)}). 사용자가 직접 쓴 글처럼 보내야 한다 — 흔적을 지우고 다시 승인받는다.")

    if (tool == "slack_send_message" and str(tool_input.get("channel_id") or "").strip() in SELF_DM
            and set(canonical(tool_input)) <= SELF_DM_KEYS):
        return  # 본인 DM — 승인 없이 보낸다(맨 위 설명의 예외)

    code = approval_code(tool, tool_input)
    path = payload.get("transcript_path") or ""
    if not path or not os.path.isfile(path):
        deny("대화 기록(transcript_path)을 찾지 못해 승인을 확인할 수 없다. 보내지 않았다. " + how_to_ask(tool, code, tool_input))

    found = approvals(path, code)
    if not found:
        deny("사용자 승인 기록이 없어 보내지 않았다. " + how_to_ask(tool, code, tool_input))

    used = load_used()
    now = dt.datetime.now(dt.timezone.utc)
    label = APPROVE_LABEL.get(tool, OTHER_LABEL)
    message = tool_input.get("message")
    problems = []
    for a in found:
        q = a["question"]
        options = [o for o in q.get("options") or [] if isinstance(o, dict)]
        chosen = next((o for o in options if o.get("label") == a["answer"]), None)
        place = destination_problems(tool, tool_input, str(q.get("question", "")))
        if not a["genuine"]:
            problems.append("승인 카드가 AskUserQuestion 호출 결과가 아니다")
        elif a["auto"]:
            problems.append("자리 비움 자동 진행·추가 질문·직접 입력은 승인이 아니다")
        elif str(a["note"]).strip():
            problems.append(f"사용자가 메모를 남겼다('{str(a['note']).strip()[:80]}') — 반영한 뒤 다시 승인받는다")
        elif chosen is None or not label_ok(a["answer"], label):
            problems.append(f"사용자가 고른 답이 '{label}'가 아니다('{a['answer']}')")
        elif tool in MESSAGE_TOOLS and same_text(chosen.get("description")) != same_text(message):
            problems.append(f"'{label}' 선택지 설명(description)에 보여 준 글과 보낼 글이 다르다(글 전체를 그대로 넣어야 한다)")
        elif tool in MESSAGE_TOOLS and chosen.get("preview") and same_text(chosen.get("preview")) != same_text(message):
            problems.append(f"'{label}' 선택지 미리보기(preview)에 보여 준 글과 보낼 글이 다르다")
        elif place:
            problems.extend(place)
        elif a["time"] is None or now - a["time"] > MAX_AGE or a["time"] - now > dt.timedelta(minutes=5):
            problems.append("승인 시각이 없거나 2시간이 넘었다")
        elif a["id"] in used:
            problems.append("이미 한 번 보낸 승인이다")
        elif mark_used(a["id"], code, tool_name):
            return
        else:
            problems.append("이미 한 번 보낸 승인이다")
    deny("승인을 확인하지 못해 보내지 않았다: " + "; ".join(dict.fromkeys(problems)) + ". " + how_to_ask(tool, code, tool_input))


def command_text(tool_name: str, tool_input: dict) -> str:
    keys = ("command", "input", "keys", "text")
    return "\n".join(str(tool_input.get(k)) for k in keys if tool_input.get(k))


def check_terminal(tool_name: str, tool_input: dict):
    text = command_text(tool_name, tool_input)
    if SLACK_WRITE_API.search(text):
        deny("터미널에서 Slack 쓰기 API 를 부르지 않는다. Slack 에 보낼 글은 Slack MCP 도구 + 사용자 승인 카드로만 보낸다.")
    if any(re.search(p, text, re.IGNORECASE) for p in TAMPER) or (re.search(PROTECTED, text) and SCRIPT_WRITE.search(text)):
        deny("대화 기록(~/.claude/projects/**/*.jsonl)과 승인 기록(~/.claude/hooks/state/)은 고치거나 지우지 않는다.")


def check_file(tool_name: str, tool_input: dict):
    paths = [tool_input.get(k) for k in ("file_path", "path", "notebook_path", "source", "destination")]
    for p in paths:
        if p and re.search(PROTECTED, os.path.expanduser(str(p))):
            deny("대화 기록(~/.claude/projects/**/*.jsonl)과 승인 기록(~/.claude/hooks/state/)은 고치거나 지우지 않는다.")


def check_paseo_answer(tool_input: dict):
    blob = json.dumps(tool_input, ensure_ascii=False)
    if "answers" in blob and ("승인 " in blob or any(f'"{label}' in blob for label in list(APPROVE_LABEL.values()) + [OTHER_LABEL])):
        deny("다른 에이전트의 Slack 승인 카드에 대신 답하지 않는다. 사용자가 직접 고른다.")


def check(payload: dict):
    tool_name = str(payload.get("tool_name") or "")
    tool_input = payload.get("tool_input") if isinstance(payload.get("tool_input"), dict) else {}
    if is_slack_tool(tool_name):
        check_slack(payload, tool_name)
    elif tool_name in TERMINAL_TOOLS:
        check_terminal(tool_name, tool_input)
    elif tool_name in FILE_TOOLS:
        check_file(tool_name, tool_input)
    elif tool_name == "mcp__paseo__respond_to_permission":
        check_paseo_answer(tool_input)


def main():
    if len(sys.argv) >= 3 and sys.argv[1] == "--code":
        tool = SHORT.get(sys.argv[2], tool_short(sys.argv[2]))
        print(approval_code(tool, json.load(sys.stdin)))
        return
    try:
        payload = json.load(sys.stdin)
        if not isinstance(payload, dict):
            raise ValueError("payload 가 dict 가 아니다")
        check(payload)
    except SystemExit:
        raise
    except Exception as e:  # 알 수 없는 오류는 막는 쪽으로
        tool_name = ""
        try:
            tool_name = str(payload.get("tool_name") or "")  # noqa: F821
        except Exception:
            pass
        if not tool_name or is_slack_tool(tool_name) or tool_name == "mcp__paseo__respond_to_permission":
            deny(f"확인 중 오류가 나 막았다({type(e).__name__}: {str(e)[:200]}).")
        # 터미널·파일 도구에서 가드 자체가 실패하면 원래 작업은 막지 않는다
        print(f"{PREFIX} 확인 중 오류: {type(e).__name__}: {e}", file=sys.stderr)


if __name__ == "__main__":
    main()
